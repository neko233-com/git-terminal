use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Write the module that embeds the locale documents.
///
/// The interface languages are data, not code. Every file in `locales/` is one
/// language, and the build discovers them on its own, so adding a language means
/// dropping in a locale file and rebuilding - no Rust change, no registry edit,
/// and no list of supported languages that can drift out of date.
fn generate_locales(root: &Path) {
    let locales = root.join("locales");
    println!("cargo:rerun-if-changed=locales");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if locales.is_dir() {
        for entry in fs::read_dir(&locales).expect("locales directory") {
            let path = entry.expect("locale entry").path();
            if path.extension().and_then(|value| value.to_str()) != Some("json") {
                continue;
            }
            let code = path
                .file_stem()
                .and_then(|value| value.to_str())
                .expect("locale file name")
                .to_owned();
            entries.push((code, path));
        }
    }
    // The order is fixed so the language list and the fallback chain are stable
    // across machines, regardless of how the file system enumerates the directory.
    entries.sort_by(|left, right| left.0.cmp(&right.0));

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs. Do not edit.\n");
    generated.push_str("/// The locale documents shipped with this build, keyed by locale code.\n");
    generated.push_str("pub static CATALOGS: &[(&str, &str)] = &[\n");
    for (code, path) in &entries {
        // The document is copied next to the generated file so the include stays
        // relative and the path never depends on the build machine's layout.
        let file_name = format!("{code}.json");
        fs::copy(path, out_dir.join(&file_name)).expect("copy locale document");
        generated.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            code, file_name
        ));
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("locales_generated.rs"), generated).expect("write generated locales");
}

fn main() {
    println!("cargo:rerun-if-changed=assets/git-terminal.ico");
    println!("cargo:rerun-if-changed=build.rs");
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    generate_locales(&root);
    let target = env::var("TARGET").unwrap();
    if !target.contains("windows") {
        return;
    }
    let version = env::var("CARGO_PKG_VERSION").unwrap();
    let parts: Vec<u16> = version
        .split('.')
        .map(|part| part.parse().expect("stable numeric package version"))
        .collect();
    assert_eq!(
        parts.len(),
        3,
        "Windows requires a three-part package version"
    );
    let numeric = format!("{},{},{},0", parts[0], parts[1], parts[2]);
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let icon = root
        .join("assets/git-terminal.ico")
        .to_string_lossy()
        .replace('\\', "\\\\");
    let script = out.join("git-terminal.rc");
    fs::write(
        &script,
        format!(
            r#"1 ICON "{icon}"
1 VERSIONINFO
FILEVERSION {numeric}
PRODUCTVERSION {numeric}
FILEOS 0x40004L
FILETYPE 1
BEGIN
 BLOCK "StringFileInfo"
 BEGIN
  BLOCK "040904b0"
  BEGIN
   VALUE "CompanyName", "neko233-com\0"
   VALUE "FileDescription", "Git-Terminal\0"
   VALUE "ProductName", "Git-Terminal\0"
   VALUE "FileVersion", "{version}\0"
   VALUE "ProductVersion", "{version}\0"
  END
 END
 BLOCK "VarFileInfo"
 BEGIN
  VALUE "Translation", 0x409, 1200
 END
END
"#
        ),
    )
    .unwrap();
    let resource = out.join(if target.contains("msvc") {
        "git-terminal.res"
    } else {
        "git-terminal-resource.o"
    });
    let status = if target.contains("msvc") {
        let compiler = env::var_os("RC").map(PathBuf::from).unwrap_or_else(|| {
            let base = PathBuf::from(env::var_os("ProgramFiles(x86)").unwrap())
                .join("Windows Kits/10/bin");
            let mut versions: Vec<_> = fs::read_dir(base)
                .unwrap()
                .flatten()
                .map(|e| e.path())
                .filter(|p| p.join("x64/rc.exe").is_file())
                .collect();
            versions.sort();
            versions
                .pop()
                .expect("Windows SDK resource compiler is required")
                .join("x64/rc.exe")
        });
        Command::new(compiler)
            .arg("/nologo")
            .arg("/fo")
            .arg(&resource)
            .arg(&script)
            .status()
    } else {
        let compiler = env::var_os("WINDRES")
            .map(PathBuf::from)
            .unwrap_or_else(|| {
                let cc = PathBuf::from(
                    env::var_os("CC_aarch64_pc_windows_gnullvm")
                        .expect("The pinned ARM64 compiler is required"),
                );
                cc.parent().unwrap().join("aarch64-w64-mingw32-windres.exe")
            });
        Command::new(compiler)
            .arg("-i")
            .arg(&script)
            .arg("-o")
            .arg(&resource)
            .args(["-O", "coff"])
            .status()
    }
    .expect("Resource compiler could not start");
    assert!(
        status.success(),
        "Git-Terminal icon resource compilation failed"
    );
    println!(
        "cargo:rustc-link-arg-bin=git-terminal={}",
        resource.display()
    );
}
