//! Application connections and OpenSSH share one deterministic view.
use crate::remote::{self, Host};
use anyhow::{Context, Result, bail, ensure};
use serde::{Deserialize, Serialize};
use std::{collections::HashSet, io::{Read, Write}, path::{Path, PathBuf}, sync::{Arc, atomic::AtomicBool}, time::Duration};

const BEGIN: &str = "# BEGIN Git-Terminal managed connections\n";
const END: &str = "# END Git-Terminal managed connections\n";
const GENERATED: &str = "# Generated by Git-Terminal. Edit connections in the application.\n";
const LIMIT: u64 = 4 * 1024 * 1024;

#[derive(Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum ImportMode { Merge, Replace }

#[derive(Serialize, Deserialize)]
struct Bundle { schema_version: u32, hosts: Vec<Host> }

pub fn ssh_root() -> PathBuf {
    std::env::var_os("SSH_ROOT_PATH").map(PathBuf::from).unwrap_or_else(|| {
        let home = if cfg!(windows) { std::env::var_os("USERPROFILE").or_else(|| std::env::var_os("HOME")) }
                   else { std::env::var_os("HOME") };
        PathBuf::from(home.unwrap_or_default()).join(".ssh")
    })
}
fn read(path: &Path) -> Result<Vec<u8>> {
    match std::fs::metadata(path) {
        Ok(meta) => { ensure!(meta.len() <= LIMIT, "SSH configuration is too large"); Ok(std::fs::read(path)?) }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(error) => Err(error.into()),
    }
}
pub fn alias(host: &Host) -> Result<String> {
    let value: String = host.name.chars().map(|c| if c.is_whitespace() { '-' } else { c }).collect();
    ensure!(!value.starts_with('-') && value.chars().all(|c| c.is_alphanumeric() || "-_.".contains(c)), "Name must be an SSH alias: letters, numbers, spaces, -, _ or .");
    Ok(value)
}
fn quote(value: &str) -> Result<String> {
    ensure!(!value.chars().any(char::is_control), "SSH configuration values cannot contain control characters");
    Ok(format!("\"{}\"", value.replace('\\', "/").replace('"', "\\\"")))
}
fn tokens(line: &str) -> Vec<String> {
    let mut words = Vec::new(); let mut word = String::new(); let mut quoted = false;
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' => quoted = !quoted,
            '#' if !quoted => break,
            '\\' if quoted && chars.peek().is_some_and(|c| matches!(c, '"' | '\\')) => word.push(chars.next().unwrap()),
            c if !quoted && (c.is_whitespace() || (c == '=' && words.is_empty())) => {
                if !word.is_empty() { words.push(std::mem::take(&mut word)); }
            }
            _ => word.push(c),
        }
    }
    if !word.is_empty() { words.push(word); }
    words
}
fn matches(pattern: &[u8], name: &[u8]) -> bool {
    let (mut p, mut n, mut star, mut back) = (0, 0, None, 0);
    while n < name.len() {
        if p < pattern.len() && (pattern[p] == b'?' || pattern[p] == name[n]) { p+=1; n+=1; }
        else if p < pattern.len() && pattern[p] == b'*' { star=Some(p); p+=1; back=n; }
        else if let Some(s) = star { back+=1; n=back; p=s+1; }
        else { return false; }
    }
    while p < pattern.len() && pattern[p] == b'*' { p+=1; }
    p == pattern.len()
}
fn expand(path: &Path) -> Result<Vec<PathBuf>> {
    let text = path.to_string_lossy();
    if !text.contains(['*', '?']) { return Ok(vec![path.to_path_buf()]); }
    let parent = path.parent().context("Invalid Include path")?;
    let pattern = path.file_name().context("Invalid Include pattern")?.to_string_lossy();
    let mut found = Vec::new();
    for directory in expand(parent)? {
        if !directory.is_dir() { continue; }
        for entry in std::fs::read_dir(directory)? {
            let entry = entry?;
            if matches(pattern.as_bytes(), entry.file_name().to_string_lossy().as_bytes()) { found.push(entry.path()); }
            ensure!(found.len() <= 256, "Too many SSH Include files");
        }
    }
    found.sort(); Ok(found)
}
fn discover(path: &Path, root: &Path, seen: &mut HashSet<PathBuf>, hosts: &mut Vec<Host>) -> Result<()> {
    if !path.is_file() { return Ok(()); }
    let path = path.canonicalize()?;
    if !seen.insert(path.clone()) { return Ok(()); }
    ensure!(seen.len() <= 256, "Too many SSH Include files");
    let bytes = read(&path)?;
    let text = std::str::from_utf8(&bytes)?.trim_start_matches('\u{feff}');
    let mut managed = false;
    for line in text.lines() {
        if line.trim() == BEGIN.trim() { managed = true; continue; }
        if line.trim() == END.trim() { managed = false; continue; }
        if managed { continue; }
        let words = tokens(line);
        if words.first().is_some_and(|w| w.eq_ignore_ascii_case("include")) {
            for item in &words[1..] {
                let expanded = if let Some(tail) = item.strip_prefix("~/") { ssh_root().parent().unwrap().join(tail) }
                    else { let path = PathBuf::from(item); if path.is_absolute() { path } else { root.join(path) } };
                for included in expand(&expanded)? { discover(&included, root, seen, hosts)?; }
            }
        } else if words.first().is_some_and(|w| w.eq_ignore_ascii_case("host")) {
            for name in &words[1..] {
                if name.contains(['*', '?', '!', '=']) || hosts.iter().any(|h| h.name.eq_ignore_ascii_case(name)) { continue; }
                let host = Host { name: name.clone(), destination: name.clone(), group: "System SSH".into(), system: true, ..Host::default() };
                host.validate()?; hosts.push(host);
            }
        }
    }
    Ok(())
}
pub fn load() -> Result<Vec<Host>> {
    let mut hosts = remote::load_managed_hosts()?;
    let root = ssh_root();
    discover(&root.join("config"), &root, &mut HashSet::new(), &mut hosts)?;
    Ok(hosts)
}
fn system_text(before: &[u8]) -> Result<String> {
    let text = std::str::from_utf8(before)?;
    let start = text.find(BEGIN);
    if let Some(start) = start {
        let end = text[start..].find(END).context("Incomplete Git-Terminal config block; repair it before saving")? + start + END.len();
        ensure!(!text[end..].contains(BEGIN), "Duplicate managed SSH block");
        return Ok(format!("{}{}", &text[..start], &text[end..]));
    }
    ensure!(!text.contains(END), "Incomplete Git-Terminal config block");
    Ok(text.to_owned())
}
fn render(hosts: &[Host]) -> Result<String> {
    let mut output = GENERATED.to_owned();
    let mut aliases = HashSet::new();
    for host in hosts {
        let name = alias(host)?;
        ensure!(aliases.insert(name.to_lowercase()), "SSH aliases collide after replacing spaces with -");
        host.validate()?;
        output.push_str(&format!("\nHost {}\n", quote(&name)?));
        // Resolve only on an explicit save/export, never during tab creation or discovery.
        let ssh = remote::ssh_executable(None)?;
        let mut command = remote::process(host, &ssh)?;
        command.args(["-G", "--", &host.destination]);
        let child = remote::OwnedProcess::spawn(command, Arc::new(AtomicBool::new(false)), Duration::from_secs(4))?;
        let mut reader = child.child.lock().stdout.take().context("SSH config reader is unavailable")?;
        let mut bytes = Vec::new(); reader.by_ref().take(LIMIT+1).read_to_end(&mut bytes)?;
        ensure!(bytes.len() as u64 <= LIMIT, "Resolved SSH configuration is too large");
        ensure!(child.child.lock().wait()?.success(), "OpenSSH could not resolve this connection configuration");
        for line in std::str::from_utf8(&bytes)?.lines() {
            let Some((key, value)) = line.split_once(' ') else { continue };
            if ["hostname", "user", "port", "identityfile", "identitiesonly", "identityagent", "proxyjump", "proxycommand", "hostkeyalias", "userknownhostsfile", "stricthostkeychecking", "preferredauthentications", "certificatefile", "pubkeyauthentication", "batchmode"].contains(&key) {
                let value = if ["identityfile", "identityagent", "certificatefile"].contains(&key) { quote(value)? } else { value.to_owned() };
                output.push_str(&format!("  {key} {value}\n"));
            }
        }
    }
    Ok(output)
}
pub fn atomic_write(path: &Path, bytes: &[u8]) -> Result<()> {
    ensure!(!path.is_symlink(), "A configuration symlink must be edited at its original target");
    std::fs::create_dir_all(path.parent().context("Missing configuration directory")?)?;
    let temp = path.with_extension(format!("{}-{}.tmp", std::process::id(), std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH)?.as_nanos()));
    let result = (|| -> Result<()> {
        let mut options = std::fs::OpenOptions::new(); options.write(true).create_new(true);
        #[cfg(unix)] { use std::os::unix::fs::OpenOptionsExt; options.mode(0o600); }
        let mut file = options.open(&temp)?; file.write_all(bytes)?; file.sync_all()?; drop(file);
        #[cfg(windows)] {
            use std::os::windows::ffi::OsStrExt;
            use windows_sys::Win32::Storage::FileSystem::*;
            let from: Vec<_> = temp.as_os_str().encode_wide().chain(Some(0)).collect();
            let to: Vec<_> = path.as_os_str().encode_wide().chain(Some(0)).collect();
            let ok = unsafe { if path.exists() { ReplaceFileW(to.as_ptr(), from.as_ptr(), std::ptr::null(), 0, std::ptr::null(), std::ptr::null()) } else { MoveFileExW(from.as_ptr(), to.as_ptr(), MOVEFILE_WRITE_THROUGH) } };
            ensure!(ok != 0, "Cannot atomically update SSH configuration: {}", std::io::Error::last_os_error());
        }
        #[cfg(not(windows))] { if path.exists() { std::fs::set_permissions(&temp, std::fs::metadata(path)?.permissions())?; } std::fs::rename(&temp, path)?; }
        Ok(())
    })();
    if temp.exists() { let _ = std::fs::remove_file(temp); }
    result
}
pub fn save(hosts: &[Host]) -> Result<()> {
    let hosts: Vec<_> = hosts.iter().filter(|h| !h.system).cloned().collect();
    let root = ssh_root(); std::fs::create_dir_all(&root)?;
    let lock = std::fs::OpenOptions::new().create(true).truncate(false).write(true).open(root.join("git-terminal.lock"))?;
    lock.try_lock().context("Another SSH configuration update is running")?;
    let config = root.join("config"); let generated = root.join("git-terminal.conf");
    let before = read(&config)?; let old_generated = read(&generated)?;
    ensure!(old_generated.is_empty() || old_generated.starts_with(GENERATED.as_bytes()), "git-terminal.conf belongs to another application; it was preserved");
    let original = system_text(&before)?;
    let rendered = render(&hosts)?;
    let after = format!("{BEGIN}Include \"git-terminal.conf\"\nHost *\n{END}{original}");
    ensure!(read(&config)? == before && read(&generated)? == old_generated, "SSH configuration changed while saving; retry");
    let backup = root.join("config.before-git-terminal");
    if !backup.exists() && !before.is_empty() { atomic_write(&backup, &before)?; }
    atomic_write(&generated, rendered.as_bytes())?;
    let result = (|| -> Result<()> { atomic_write(&config, after.as_bytes())?; remote::write_hosts(&hosts) })();
    if let Err(error) = result {
        atomic_write(&generated, &old_generated)?;
        atomic_write(&config, &before)?;
        return Err(error);
    }
    Ok(())
}
pub fn import(path: &Path, mode: ImportMode) -> Result<usize> {
    let bytes = read(path)?;
    let incoming = if bytes.iter().find(|c| !c.is_ascii_whitespace()).is_some_and(|c| matches!(c, b'[' | b'{')) {
        if bytes.iter().find(|c| !c.is_ascii_whitespace()) == Some(&b'[') { serde_json::from_slice::<Vec<Host>>(&bytes)? }
        else { let bundle: Bundle = serde_json::from_slice(&bytes)?; ensure!(bundle.schema_version == 1, "Unsupported host export version"); bundle.hosts }
    } else { remote::import_config(path)? };
    for host in &incoming { host.validate()?; alias(host)?; }
    let mut hosts = if mode == ImportMode::Replace { Vec::new() } else { remote::load_managed_hosts()? };
    let mut added = 0;
    for mut host in incoming {
        if hosts.iter().any(|h| h.name.eq_ignore_ascii_case(&host.name)) { continue; }
        host.system = false; hosts.push(host); added+=1;
    }
    save(&hosts)?; Ok(added)
}
pub fn export(path: &Path) -> Result<()> {
    ensure!(path != remote::config_path() && path != ssh_root().join("config") && path != ssh_root().join("git-terminal.conf"), "Choose a separate export file");
    let hosts = remote::load_managed_hosts()?;
    if path.extension().is_some_and(|s| s.eq_ignore_ascii_case("json")) {
        atomic_write(path, &serde_json::to_vec_pretty(&Bundle { schema_version: 1, hosts })?)
    } else { atomic_write(path, render(&hosts)?.as_bytes()) }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn config_tokens_and_managed_boundaries() {
        assert_eq!(tokens("Host = \"my server\" work # comment"), ["Host", "my server", "work"]);
        assert_eq!(tokens("IdentityFile \"C:\\Users\\my key#1\""), ["IdentityFile", "C:\\Users\\my key#1"]);
        let original = "# preserved\r\nHost legacy\r\n  HostName example.invalid\r\n";
        assert_eq!(system_text(format!("{BEGIN}Include file\nHost *\n{END}{original}").as_bytes()).unwrap(), original);
        assert!(system_text(format!("{BEGIN}Include file\n").as_bytes()).is_err());
        assert!(matches(b"*.conf", b"ab.conf")); assert!(!matches(b"?.conf", b"ab.conf"));
    }
}
